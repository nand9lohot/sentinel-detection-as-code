"""Generate the detection catalog and ATT&CK Navigator layer from the rules."""

from __future__ import annotations

import json
import re

from sdac.rules import ROOT, Rule

CATALOG_PATH = ROOT / "docs" / "catalog.md"
LAYER_PATH = ROOT / "docs" / "attack-layer.json"


def _slug(tactic: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "-", tactic).lower()


def _technique_link(technique: str) -> str:
    return f"[{technique}](https://attack.mitre.org/techniques/{technique.replace('.', '/')}/)"


def render_catalog(rules: list[Rule]) -> str:
    lines = [
        "# Detection catalog",
        "",
        "Generated by `sdac catalog`. Do not edit by hand.",
        "",
        "| Detection | Severity | Tactics | Techniques | Tables | Version |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for rule in sorted(rules, key=lambda r: r.name):
        data = rule.data
        lines.append(
            f"| [{rule.name}](../{rule.relpath}) | {data['severity']} | {', '.join(data['tactics'])} | "
            f"{', '.join(_technique_link(t) for t in data['relevantTechniques'])} | "
            f"{', '.join(rule.data_types)} | {data['version']} |"
        )
    return "\n".join(lines) + "\n"


def render_layer(rules: list[Rule]) -> str:
    techniques = {}
    for rule in sorted(rules, key=lambda r: r.name):
        for tactic in rule.data["tactics"]:
            for technique in rule.data["relevantTechniques"]:
                entry = techniques.setdefault(
                    (technique, tactic),
                    {"techniqueID": technique, "tactic": _slug(tactic), "score": 0, "comment": []},
                )
                entry["score"] += 1
                entry["comment"].append(rule.name)
    items = []
    for key in sorted(techniques):
        entry = dict(techniques[key])
        entry["comment"] = "; ".join(entry["comment"])
        items.append(entry)
    layer = {
        "name": "Sentinel detection coverage",
        "description": "Generated by sdac catalog. Score is the number of deployed rules.",
        "versions": {"layer": "4.5"},
        "domain": "enterprise-attack",
        "techniques": items,
        "gradient": {"colors": ["#ffffff", "#2e7d32"], "minValue": 0, "maxValue": 3},
    }
    return json.dumps(layer, indent=2) + "\n"


def stale_outputs(rules: list[Rule]) -> list[str]:
    stale = []
    for path, content in ((CATALOG_PATH, render_catalog(rules)), (LAYER_PATH, render_layer(rules))):
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(path.relative_to(ROOT).as_posix())
    return stale


def write_outputs(rules: list[Rule]) -> None:
    CATALOG_PATH.parent.mkdir(parents=True, exist_ok=True)
    CATALOG_PATH.write_text(render_catalog(rules), encoding="utf-8")
    LAYER_PATH.write_text(render_layer(rules), encoding="utf-8")
